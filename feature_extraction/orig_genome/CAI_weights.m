load('Y_genes.mat');

codons_cnt = containers.Map; % codons counts in refseq
aa_max = containers.Map; % for each aa, counts of most frequent codon
for i = 1:1:height(Y_genes)
    refgene = upper(Y_genes{i,2});
    for j = 4:3:(length(refgene)-3)
        codon = refgene(j:j+2);
        aa = nt2aa(codon);
        if (codons_cnt.isKey(codon))
            codons_cnt(codon) = codons_cnt(codon) + 1;
        else
            codons_cnt(codon) = 1;
        end
        if (~aa_max.isKey(aa)) || (codons_cnt(codon) > aa_max(aa))
            aa_max(aa) = codons_cnt(codon);
        end
    end    
end

codons = [  "AAA" "AAC" "AAG" "AAT" ...
            "ACA" "ACC" "ACG" "ACT" ...
            "AGA" "AGC" "AGG" "AGT" ...
            "ATA" "ATC" "ATG" "ATT" ...
            "CAA" "CAC" "CAG" "CAT" ...
            "CCA" "CCC" "CCG" "CCT" ...
            "CGA" "CGC" "CGG" "CGT" ...
            "CTA" "CTC" "CTG" "CTT" ...
            "GAA" "GAC" "GAG" "GAT" ...
            "GCA" "GCC" "GCG" "GCT" ...
            "GGA" "GGC" "GGG" "GGT" ...
            "GTA" "GTC" "GTG" "GTT" ...
            "TAA" "TAC" "TAG" "TAT" ...
            "TCA" "TCC" "TCG" "TCT" ...
            "TGA" "TGC" "TGG" "TGT" ...
            "TTA" "TTC" "TTG" "TTT" ];
CAI_w_map = containers.Map;
for i = 1:1:length(codons)
    codon = char(codons(i));
    aa = nt2aa(codon);
    if (codons_cnt.isKey(codon))
        CAI_w_map(codon) = codons_cnt(codon)/aa_max(aa);
    else
        CAI_w_map(codon) = 0.5/aa_max(aa);
    end
end

save CAI_w_map.mat CAI_w_map;